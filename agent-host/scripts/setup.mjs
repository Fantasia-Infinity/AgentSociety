#!/usr/bin/env node

import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { createInterface } from "node:readline/promises";
import { stdin, stdout } from "node:process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { homedir, userInfo } from "node:os";
import { Writable } from "node:stream";

const agentHostDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(agentHostDir, "..");
const args = parseArguments(process.argv.slice(2));
const dshHome = resolve(
  process.env.DSH_HOME?.trim() || join(homedir(), ".dsh"),
);
const configPath = resolve(
  args.config ||
    process.env.AGENT_SETUP_CONFIG_PATH ||
    process.env.AGENT_ENV_FILE ||
    defaultAgentConfigPath(),
);
const legacyConfigPaths = [
  oldCentralConfigPath(),
  resolve(repositoryRoot, ".private", "env", "agent.env"),
  resolve(repositoryRoot, ".env.agent"),
  resolve(process.cwd(), ".private", "env", "agent.env"),
  resolve(process.cwd(), ".env.agent"),
];
const completionMarker = resolve(agentHostDir, ".setup-complete");

async function main() {
  assertNodeVersion();
  if (args.bootstrap) {
    bootstrapRuntime();
    return;
  }

  const sourcePath =
    existsSync(configPath)
      ? configPath
      : args.explicitConfig
        ? undefined
        : legacyConfigPaths.find((path) => existsSync(path));
  const existingText = sourcePath
    ? normalizeConfigHeader(readFileSync(sourcePath, "utf8"))
    : "# Generated by AgentSociety setup. Non-secret settings live here; secrets use the selected credential backend.\n";
  const existing = parseEnv(existingText);
  const workspaceRoot = resolve(
    process.env.AGENT_SETUP_WORKSPACE?.trim() ||
      existing.AGENT_WORKSPACE_ROOT?.trim() ||
      homedir(),
  );
  mkdirSync(workspaceRoot, { recursive: true, mode: 0o700 });

  const credentials = await createCredentialStore(
    args.credentials,
    configPath,
    existing.AGENT_CREDENTIAL_FILE,
  );
  const { values, hubPasswordMode, mode } = await collectValues(
    existing,
    credentials,
    workspaceRoot,
  );
  writeConfig(existingText, values, configPath);
  writeFileSync(completionMarker, `${new Date().toISOString()}\n`, {
    encoding: "utf8",
    mode: 0o600,
  });
  chmodSync(completionMarker, 0o600);

  console.log(`\nSaved non-secret Agent configuration to ${configPath}`);
  if (sourcePath && sourcePath !== configPath) {
    console.log(
      `Migrated readable settings from legacy config ${sourcePath}; the legacy file was kept unchanged.`,
    );
  }
  console.log(`Credential backend: ${credentials.summary}`);
  if (credentials.backend === "file") {
    console.warn(
      `WARNING: credentials are persisted in ${credentials.credentialFile} with mode 0600.`,
    );
  } else if (credentials.backend === "env") {
    console.warn(
      "Credentials are environment-only and will not survive a new shell. Export them before starting AgentSociety.",
    );
  }
  console.log(`Mode: ${mode}`);
  console.log(`Permission: ${values.AGENT_DSH_PERMISSION_MODE}`);
  if (mode === "hub-worker" && hubPasswordMode && !args.configureOnly) {
    process.env.AGENT_ENV_FILE = configPath;
    console.log("Registering this machine as a Hub worker...");
    run(process.execPath, ["dist/src/cli.js", "connect", "--non-interactive"]);
    console.log("Hub node credential registered and saved.");
  } else if (mode === "hub-worker") {
    console.log("Next: agent connect   # register this machine as a Hub worker");
  }
  console.log("Next: agent doctor    # static checks; add --live for network tests");
  console.log("Next: agent web       # optional local DSH Web bridge");
}

function parseArguments(argv) {
  const result = {
    mode: process.env.AGENT_SETUP_MODE?.trim() || "",
    config: process.env.AGENT_SETUP_CONFIG_PATH?.trim() || "",
    credentials: process.env.AGENT_SETUP_CREDENTIALS?.trim() || "auto",
    nonInteractive: false,
    bootstrap: false,
    configureOnly: false,
    explicitConfig: Boolean(
      process.env.AGENT_SETUP_CONFIG_PATH?.trim() ||
        process.env.AGENT_ENV_FILE?.trim(),
    ),
  };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    const next = argv[index + 1];
    if (arg === "--mode") {
      result.mode = next || "";
      index += 1;
    } else if (arg?.startsWith("--mode=")) {
      result.mode = arg.slice("--mode=".length);
    } else if (arg === "--config") {
      result.config = next || "";
      result.explicitConfig = true;
      index += 1;
    } else if (arg?.startsWith("--config=")) {
      result.config = arg.slice("--config=".length);
      result.explicitConfig = true;
    } else if (arg === "--credentials") {
      result.credentials = next || "";
      index += 1;
    } else if (arg?.startsWith("--credentials=")) {
      result.credentials = arg.slice("--credentials=".length);
    } else if (arg === "--non-interactive") {
      result.nonInteractive = true;
    } else if (arg === "--bootstrap" || arg === "--repair") {
      result.bootstrap = true;
    } else if (arg === "--configure-only") {
      // Kept for existing scripts and tests. Setup is configuration-only now.
      result.configureOnly = true;
    } else if (arg === "--help" || arg === "-h") {
      console.log(`Usage: agent setup [options]

Options:
  --mode local|hub-worker|dispatch-only
  --config <path>                 user configuration file override
  --credentials auto|env|file     credential backend (file is explicit and 0600)
  --non-interactive               require values from environment/configuration
  --bootstrap                     install/build the AgentSociety runtime once
  --repair                        alias for --bootstrap
`);
      process.exit(0);
    } else if (arg) {
      throw new Error(`Unknown setup option: ${arg}`);
    }
  }
  if (!result.config && process.env.AGENT_ENV_FILE?.trim()) {
    result.config = process.env.AGENT_ENV_FILE.trim();
    result.explicitConfig = true;
  }
  if (!["auto", "env", "file"].includes(result.credentials)) {
    throw new Error("--credentials must be auto, env, or file");
  }
  if (
    result.mode &&
    !["local", "hub-worker", "dispatch-only"].includes(result.mode)
  ) {
    throw new Error("--mode must be local, hub-worker, or dispatch-only");
  }
  return result;
}

function defaultAgentConfigPath() {
  return join(dshHome, ".env");
}

function oldCentralConfigPath() {
  const configHome =
    process.platform === "win32"
      ? process.env.APPDATA?.trim() || join(homedir(), "AppData", "Roaming")
      : process.env.XDG_CONFIG_HOME?.trim() || join(homedir(), ".config");
  return join(configHome, "agentsociety", "agent.env");
}

function bootstrapRuntime() {
  run(npmCommand(), ["ci", "--ignore-scripts"]);
  run(process.execPath, ["scripts/patch-pi-brace-expansion.mjs"]);
  run(process.execPath, ["scripts/patch-pi-brace-expansion.mjs", "--check"]);
  run(npmCommand(), ["run", "build"]);
  console.log("AgentSociety runtime bootstrap is complete.");
}

function interactiveTerminal() {
  return Boolean(!args.nonInteractive && stdin.isTTY && stdout.isTTY);
}

function normalizeConfigHeader(text) {
  return text
    .replace(
      "# Generated by AgentSociety setup. This file contains secrets; do not commit it.",
      "# Generated by AgentSociety setup. Non-secret settings live here; secrets use the selected credential backend.",
    )
    .replace(
      "# Generated by AgentSociety setup. Secret values live in the system credential store.",
      "# Generated by AgentSociety setup. Non-secret settings live here; secrets use the selected credential backend.",
    );
}

async function collectValues(existingValues, credentials, workspaceRoot) {
  const namespace =
    process.env.AGENT_CREDENTIAL_NAMESPACE?.trim() || "AgentSociety";
  const interactive = interactiveTerminal();
  const mutedOutput = new MutedOutput();
  const terminal = interactive
    ? createInterface({ input: stdin, output: mutedOutput, terminal: true })
    : undefined;
  const values = {
    AGENT_CREDENTIAL_BACKEND: credentials.backend,
    AGENT_CREDENTIAL_FILE:
      credentials.backend === "file" ? credentials.credentialFile : null,
    AGENT_HUB_NODE_TOKEN: null,
  };
  let hubPasswordMode = false;

  try {
    const mode = await selectMode(existingValues, terminal, interactive);
    const existingRemoteBase =
      process.env.AGENT_REMOTE_BASE_URL?.trim() ||
      process.env.LLM_BASE_URL?.trim() ||
      existingValues.AGENT_REMOTE_BASE_URL ||
      existingValues.LLM_BASE_URL ||
      (existingValues.AGENT_DSH_PROVIDER ||
      existingValues.AGENT_SOCIETY_PROVIDER ||
      existingValues.AGENT_DSH_MODEL ||
      existingValues.AGENT_SOCIETY_MODEL ||
      process.env.AGENT_DSH_PROVIDER?.trim() ||
      process.env.AGENT_DSH_MODEL?.trim() ||
      process.env.DSH_PROVIDER?.trim() ||
      process.env.DSH_MODEL?.trim()
        ? "https://api.deepseek.com"
        : "") ||
      "";
    const existingRemoteModel =
      process.env.AGENT_REMOTE_MODEL?.trim() ||
      process.env.LLM_MODEL?.trim() ||
      existingValues.AGENT_REMOTE_MODEL ||
      existingValues.LLM_MODEL ||
      process.env.AGENT_DSH_MODEL?.trim() ||
      process.env.DSH_MODEL?.trim() ||
      existingValues.AGENT_DSH_MODEL ||
      existingValues.AGENT_SOCIETY_MODEL ||
      "";
    const existingPiProvider =
      process.env.PI_PROVIDER?.trim() || existingValues.PI_PROVIDER || "";
    const existingPiModel =
      process.env.PI_MODEL?.trim() || existingValues.PI_MODEL || "";
    const usePiConfig =
      Boolean(existingPiProvider && existingPiModel) &&
      !existingRemoteBase &&
      !existingRemoteModel;

    if (mode === "local" || mode === "hub-worker" || mode === "dispatch-only") {
      if (usePiConfig) {
        values.PI_PROVIDER = existingPiProvider;
        values.PI_MODEL = existingPiModel;
        values.AGENT_REMOTE_BASE_URL = null;
        values.AGENT_REMOTE_MODEL = null;
      } else {
        const provider = existingRemoteBase && existingRemoteModel
          ? "existing"
          : await selectProvider(terminal, interactive);
        const model = await collectModelValues(
          provider,
          existingRemoteBase,
          existingRemoteModel,
          terminal,
          interactive,
        );
        values.AGENT_REMOTE_BASE_URL = model.baseUrl;
        values.AGENT_REMOTE_MODEL = model.model;
        values.AGENT_DSH_PROVIDER = model.dshProvider;
        values.AGENT_DSH_MODEL = model.model;
        values.PI_PROVIDER = null;
        values.PI_MODEL = null;

        const modelCredential = credentialReference(existingValues, "model");
        const configuredModelKey = configuredSecret(
          existingValues,
          credentials,
          modelCredential,
          "AGENT_REMOTE_API_KEY",
          "LLM_API_KEY",
          "remote model",
        );
        const modelApiKey = await obtainSecret(
          terminal,
          mutedOutput,
          "Model API key",
          configuredModelKey,
          credentials,
          "AGENT_REMOTE_API_KEY",
        );
        rejectUnsupportedEnvCharacters("Model API key", modelApiKey);
        credentials.write(
          modelCredential,
          modelApiKey,
          "remote model",
          "AGENT_REMOTE_API_KEY",
        );
        setCredentialReferences(
          values,
          "AGENT_REMOTE_API_KEY",
          modelCredential,
          credentials,
        );
      }
    }

    if (mode === "local") {
      clearHubValues(values);
    } else {
      const configuredHubUrl =
        process.env.AGENT_HUB_URL?.trim() ||
        existingValues.AGENT_HUB_URL ||
        "";
      const hubUrl = interactive
        ? await askVisible(
            terminal,
            "Hub URL",
            configuredHubUrl,
          )
        : configuredHubUrl;
      if (!hubUrl || hubUrl === "-") {
        throw new Error(
          "Hub URL is required for hub-worker and dispatch-only modes",
        );
      }
      rejectUnsupportedEnvCharacters("Hub URL", hubUrl);
      if (looksLikePlaceholder(hubUrl)) throw new Error("Hub URL is required");
      validateUrl(hubUrl, "Hub URL");

      const configuredUsername =
        process.env.AGENT_HUB_USERNAME?.trim() ||
        existingValues.AGENT_HUB_USERNAME ||
        "";
      const hubUsername = interactive
        ? await askVisible(terminal, "Hub username", configuredUsername)
        : configuredUsername;
      if (hubUsername) {
        rejectUnsupportedEnvCharacters("Hub username", hubUsername);
        const passwordReference = {
          service:
            process.env.AGENT_HUB_PASSWORD_CREDENTIAL_SERVICE?.trim() ||
            existingValues.AGENT_HUB_PASSWORD_CREDENTIAL_SERVICE ||
            `${namespace} Hub Password`,
          account:
            process.env.AGENT_HUB_PASSWORD_CREDENTIAL_ACCOUNT?.trim() ||
            existingValues.AGENT_HUB_PASSWORD_CREDENTIAL_ACCOUNT ||
            hubUsername,
          ...(process.env.AGENT_HUB_PASSWORD_KEYCHAIN_SERVICE?.trim() ||
          existingValues.AGENT_HUB_PASSWORD_KEYCHAIN_SERVICE
            ? {
                legacy: {
                  service:
                    process.env.AGENT_HUB_PASSWORD_KEYCHAIN_SERVICE?.trim() ||
                    existingValues.AGENT_HUB_PASSWORD_KEYCHAIN_SERVICE,
                  account:
                    process.env.AGENT_HUB_PASSWORD_KEYCHAIN_ACCOUNT?.trim() ||
                    existingValues.AGENT_HUB_PASSWORD_KEYCHAIN_ACCOUNT,
                },
              }
            : {}),
        };
        const configuredHubPassword = configuredSecret(
          existingValues,
          credentials,
          passwordReference,
          "AGENT_HUB_PASSWORD",
          undefined,
          "Hub password",
        );
        const hubPassword = await obtainSecret(
          terminal,
          mutedOutput,
          "Hub password",
          configuredHubPassword,
          credentials,
          "AGENT_HUB_PASSWORD",
        );
        rejectUnsupportedEnvCharacters("Hub password", hubPassword);
        credentials.write(
          passwordReference,
          hubPassword,
          "Hub password",
          "AGENT_HUB_PASSWORD",
        );
        values.AGENT_HUB_URL = hubUrl;
        values.AGENT_HUB_USERNAME = hubUsername;
        setCredentialReferences(
          values,
          "AGENT_HUB_PASSWORD",
          passwordReference,
          credentials,
        );
        clearHubTokenValues(values);
        hubPasswordMode = true;
      } else {
        console.warn(
          "Hub token mode is deprecated; register a password account and rerun setup.",
        );
        const hubCredential = credentialReference(existingValues, "hub");
        const configuredHubToken = configuredSecret(
          existingValues,
          credentials,
          hubCredential,
          "AGENT_HUB_TOKEN",
          undefined,
          "Hub",
        );
        const hubToken = await obtainSecret(
          terminal,
          mutedOutput,
          "Hub token",
          configuredHubToken,
          credentials,
          "AGENT_HUB_TOKEN",
        );
        if (hubToken.length < 24) {
          throw new Error("Hub token must contain at least 24 characters");
        }
        rejectUnsupportedEnvCharacters("Hub token", hubToken);
        credentials.write(
          hubCredential,
          hubToken,
          "Hub",
          "AGENT_HUB_TOKEN",
        );
        values.AGENT_HUB_URL = hubUrl;
        values.AGENT_HUB_USERNAME = null;
        values.AGENT_HUB_PASSWORD = null;
        setCredentialReferences(
          values,
          "AGENT_HUB_TOKEN",
          hubCredential,
          credentials,
        );
        clearHubPasswordValues(values);
      }
    }

    if (mode !== "local") {
      const nodeCredential = credentialReference(existingValues, "node");
      const configuredNodeToken = configuredSecret(
        existingValues,
        credentials,
        nodeCredential,
        "AGENT_HUB_NODE_TOKEN",
        undefined,
        "Hub node credential",
      );
      if (configuredNodeToken) {
        rejectUnsupportedEnvCharacters("Hub node credential", configuredNodeToken);
        credentials.write(
          nodeCredential,
          configuredNodeToken,
          "Hub node credential",
          "AGENT_HUB_NODE_TOKEN",
        );
        setCredentialReferences(
          values,
          "AGENT_HUB_NODE_TOKEN",
          nodeCredential,
          credentials,
        );
      }
    }

    const webEnabled =
      mode !== "local" &&
      (interactive
        ? await askYesNo(
            terminal,
            "Enable optional DSH Web Bridge capability?",
            existingValues.AGENT_HUB_DSH_WEB === "1",
          )
        : existingValues.AGENT_HUB_DSH_WEB === "1");
    values.AGENT_HUB_DSH_WEB = webEnabled ? "1" : null;
    values.AGENT_HUB_RECEIVE_DISABLED =
      mode === "dispatch-only" ? "1" : null;

    const permission = await selectPermission(
      existingValues,
      terminal,
      interactive,
    );
    values.AGENT_REMOTE_TOOL_POLICY = permission.remote;
    values.AGENT_DSH_PERMISSION_MODE = permission.dsh;
    values.AGENT_WORKSPACE_ROOT = workspaceRoot;
    values.AGENT_CREDENTIAL_BACKEND = credentials.backend;
    values.AGENT_CREDENTIAL_FILE =
      credentials.backend === "file" ? credentials.credentialFile : null;

    return { values, hubPasswordMode, mode };
  } finally {
    terminal?.close();
  }
}

async function selectMode(existingValues, terminal, interactive) {
  const configured =
    args.mode ||
    process.env.AGENT_SETUP_MODE?.trim() ||
    (existingValues.AGENT_HUB_RECEIVE_DISABLED === "1"
      ? "dispatch-only"
      : existingValues.AGENT_HUB_URL || process.env.AGENT_HUB_URL
        ? "hub-worker"
        : "");
  if (configured) return configured;
  if (!interactive) return "local";
  return askChoice(
    terminal,
    "How will this installation be used?",
    [
      ["local", "本机使用"],
      ["hub-worker", "Hub worker（接收远程任务）"],
      ["dispatch-only", "dispatch-only（只派发，不接收）"],
    ],
    "local",
  );
}

async function selectProvider(terminal, interactive) {
  const configured = process.env.AGENT_SETUP_PROVIDER?.trim();
  if (configured) {
    if (!["deepseek", "custom", "existing"].includes(configured)) {
      throw new Error(
        "AGENT_SETUP_PROVIDER must be deepseek, custom, or existing",
      );
    }
    return configured;
  }
  if (!interactive) return "deepseek";
  return askChoice(
    terminal,
    "Model provider",
    [
      ["deepseek", "DeepSeek official preset"],
      ["existing", "Reuse existing dsh/Pi-compatible settings"],
      ["custom", "Custom OpenAI-compatible endpoint"],
    ],
    "deepseek",
  );
}

async function collectModelValues(
  provider,
  existingBase,
  existingModel,
  terminal,
  interactive,
) {
  if (provider === "existing") {
    if (!existingBase || !existingModel) {
      throw new Error(
        "No complete existing model configuration was found; choose custom or deepseek.",
      );
    }
    return {
      baseUrl: existingBase,
      model: existingModel,
      dshProvider: "deepseek-official",
    };
  }
  const defaultBase =
    provider === "deepseek" ? "https://api.deepseek.com" : existingBase;
  const defaultModel =
    provider === "deepseek" ? "deepseek-v4-flash" : existingModel;
  const baseUrl = interactive
    ? await askVisible(terminal, "OpenAI-compatible model URL", defaultBase)
    : defaultBase;
  const model = interactive
    ? await askVisible(terminal, "Model ID", defaultModel)
    : defaultModel;
  if (!baseUrl || looksLikePlaceholder(baseUrl)) {
    throw new Error("Model URL is required");
  }
  if (!model || looksLikePlaceholder(model)) {
    throw new Error("Model ID is required");
  }
  rejectUnsupportedEnvCharacters("Model URL", baseUrl);
  rejectUnsupportedEnvCharacters("Model ID", model);
  validateUrl(baseUrl, "Model URL");
  return {
    baseUrl,
    model,
    dshProvider: "deepseek-official",
  };
}

async function selectPermission(existingValues, terminal, interactive) {
  const currentRemote =
    process.env.AGENT_REMOTE_TOOL_POLICY?.trim() ||
    existingValues.AGENT_REMOTE_TOOL_POLICY ||
    "";
  const currentDsh =
    process.env.AGENT_DSH_PERMISSION_MODE?.trim() ||
    existingValues.AGENT_DSH_PERMISSION_MODE ||
    "";
  if (currentRemote && currentDsh) {
    return { remote: currentRemote, dsh: currentDsh };
  }
  if (currentRemote) {
    return {
      remote: currentRemote,
      dsh: currentRemote === "full" ? "workspace-write" : "read-only",
    };
  }
  if (currentDsh) {
    return {
      remote: currentDsh === "read-only" ? "read_only" : "full",
      dsh: currentDsh,
    };
  }
  const choice = interactive
    ? await askChoice(
        terminal,
        "Remote tool permission",
        [
          ["read-only", "read-only"],
          ["workspace-write", "workspace-write（推荐）"],
          ["full", "full"],
        ],
        "workspace-write",
      )
    : "workspace-write";
  const values = {
    "read-only": { remote: "read_only", dsh: "read-only" },
    "workspace-write": { remote: "full", dsh: "workspace-write" },
    full: { remote: "full", dsh: "danger-full-access" },
  };
  return values[choice];
}

function clearHubValues(values) {
  values.AGENT_HUB_URL = null;
  values.AGENT_HUB_USERNAME = null;
  values.AGENT_HUB_RECEIVE_DISABLED = null;
  values.AGENT_HUB_DSH_WEB = null;
  clearHubPasswordValues(values);
  clearHubTokenValues(values);
  values.AGENT_HUB_NODE_TOKEN = null;
  values.AGENT_HUB_NODE_TOKEN_CREDENTIAL_SERVICE = null;
  values.AGENT_HUB_NODE_TOKEN_CREDENTIAL_ACCOUNT = null;
  values.AGENT_HUB_NODE_TOKEN_KEYCHAIN_SERVICE = null;
  values.AGENT_HUB_NODE_TOKEN_KEYCHAIN_ACCOUNT = null;
}

function clearHubPasswordValues(values) {
  values.AGENT_HUB_PASSWORD = null;
  values.AGENT_HUB_PASSWORD_CREDENTIAL_SERVICE = null;
  values.AGENT_HUB_PASSWORD_CREDENTIAL_ACCOUNT = null;
  values.AGENT_HUB_PASSWORD_KEYCHAIN_SERVICE = null;
  values.AGENT_HUB_PASSWORD_KEYCHAIN_ACCOUNT = null;
}

function clearHubTokenValues(values) {
  values.AGENT_HUB_TOKEN = null;
  values.AGENT_HUB_TOKEN_CREDENTIAL_SERVICE = null;
  values.AGENT_HUB_TOKEN_CREDENTIAL_ACCOUNT = null;
  values.AGENT_HUB_TOKEN_KEYCHAIN_SERVICE = null;
  values.AGENT_HUB_TOKEN_KEYCHAIN_ACCOUNT = null;
}

function setCredentialReferences(values, key, reference, credentials) {
  values[key] = null;
  if (key === "AGENT_REMOTE_API_KEY") values.LLM_API_KEY = null;
  values[`${key}_KEYCHAIN_SERVICE`] = null;
  values[`${key}_KEYCHAIN_ACCOUNT`] = null;
  values[`${key}_CREDENTIAL_SERVICE`] = null;
  values[`${key}_CREDENTIAL_ACCOUNT`] = null;
  if (credentials.backend === "keychain") {
    values[`${key}_CREDENTIAL_SERVICE`] = reference.service;
    values[`${key}_CREDENTIAL_ACCOUNT`] = reference.account;
  }
}

function configuredSecret(
  existingValues,
  credentials,
  reference,
  primaryKey,
  aliasKey,
  label,
) {
  if (credentials.backend === "env") {
    return (
      process.env[primaryKey]?.trim() ||
      (aliasKey ? process.env[aliasKey]?.trim() : "") ||
      ""
    );
  }
  return (
    process.env[primaryKey]?.trim() ||
    (aliasKey ? process.env[aliasKey]?.trim() : "") ||
    existingValues[primaryKey] ||
    (aliasKey ? existingValues[aliasKey] : "") ||
    credentials.read(reference, label, primaryKey) ||
    ""
  );
}

async function obtainSecret(
  terminal,
  output,
  label,
  configured,
  credentials,
  envKey,
) {
  const canPrompt =
    interactiveTerminal() &&
    (credentials.backend !== "env" || credentials.allowInteractiveEnv === true);
  if (!configured && credentials.backend === "env" && !canPrompt) {
    throw new Error(
      `No ${label} was supplied. Export ${envKey} and rerun setup, or explicitly choose --credentials file.`,
    );
  }
  const value = canPrompt ? await askSecret(terminal, output, label, configured) : configured;
  if (!value || looksLikePlaceholder(value)) {
    throw new Error(`${label} is required`);
  }
  return value;
}

async function createCredentialStore(requested, configPathValue, existingFile) {
  const configuredFile =
    process.env.AGENT_CREDENTIAL_FILE?.trim() || existingFile?.trim();
  const credentialFile = resolve(
    configuredFile || join(dirname(configPathValue), "credentials.env"),
  );
  if (requested === "file") return fileCredentialStore(credentialFile);
  if (requested === "env") return environmentCredentialStore();
  if (configuredFile && requested === "auto") {
    return fileCredentialStore(credentialFile);
  }

  let store;
  try {
    const { Entry } = await import("@napi-rs/keyring");
    store = {
      backend: "keychain",
      summary: "system credential store (Keychain/Credential Manager/Secret Service)",
      credentialFile: undefined,
      allowInteractiveEnv: false,
      read(reference, label) {
        try {
          const password =
            new Entry(reference.service, reference.account).getPassword() ||
            undefined;
          if (password || !reference.legacy) return password;
          return readLegacyCredential(reference.legacy, Entry);
        } catch {
          return undefined;
        }
      },
      write(reference, secret, label) {
        try {
          new Entry(reference.service, reference.account).setPassword(secret);
        } catch {
          if (requested === "auto") {
            store.backend = "env";
            store.summary = "environment variables only (system store unavailable; not persisted)";
            store.allowInteractiveEnv = true;
            store.read = (_reference, _label, key) =>
              process.env[key]?.trim() || undefined;
            store.write = (_reference, secret, _label, key) => {
              if (key) process.env[key] = secret;
            };
            console.warn(
              "System credential store is unavailable; falling back to environment-only credentials. No secret was written to disk.",
            );
            return;
          }
          throw new Error(
            `Could not save the ${label} credential in the system store; rerun with --credentials file if this host has no usable keychain`,
          );
        }
      },
    };
    return store;
  } catch {
    console.warn(
      "System credential store unavailable; defaulting to environment-only credentials. Use --credentials file only if you explicitly accept 0600 file storage.",
    );
    return environmentCredentialStore();
  }
}

function environmentCredentialStore() {
  return {
    backend: "env",
    summary: "environment variables only (not persisted)",
    credentialFile: undefined,
    read() {
      return undefined;
    },
    write() {},
  };
}

function fileCredentialStore(path) {
  return {
    backend: "file",
    summary: "explicit 0600 credential file",
    credentialFile: path,
    read(_reference, label, key) {
      return readFileCredential(path, key, label);
    },
    write(_reference, secret, label, key) {
      writeFileCredential(path, key, secret, label);
    },
  };
}

function readFileCredential(path, key, label) {
  if (!existsSync(path)) return undefined;
  assertCredentialFileMode(path, label);
  return parseEnv(readFileSync(path, "utf8"))[key]?.trim() || undefined;
}

function writeFileCredential(path, key, value, label) {
  if (/\r|\n/u.test(value)) {
    throw new Error(`${label} cannot contain newlines`);
  }
  mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
  if (process.platform !== "win32") chmodSync(dirname(path), 0o700);
  const original = existsSync(path) ? readFileSync(path, "utf8") : "";
  const lines = original.split(/\r?\n/u);
  let replaced = false;
  const next = lines.map((line) => {
    const match = line.match(/^\s*([A-Z][A-Z0-9_]*)\s*=/u);
    if (!match || match[1] !== key) return line;
    replaced = true;
    return `${key}=${dotenvValue(value)}`;
  });
  if (!replaced) {
    if (next.at(-1)?.trim()) next.push("");
    next.push(`${key}=${dotenvValue(value)}`);
  }
  const temporary = `${path}.${process.pid}.tmp`;
  writeFileSync(temporary, `${next.join("\n").replace(/\n+$/u, "")}\n`, {
    encoding: "utf8",
    mode: 0o600,
  });
  if (process.platform !== "win32") chmodSync(temporary, 0o600);
  renameSync(temporary, path);
  if (process.platform !== "win32") chmodSync(path, 0o600);
}

function assertCredentialFileMode(path, label) {
  if (process.platform === "win32") return;
  let mode;
  try {
    mode = statSync(path).mode & 0o777;
  } catch {
    throw new Error(`Could not inspect the ${label}`);
  }
  if (mode !== 0o600) {
    throw new Error(
      `The ${label} must have permissions 0600; run chmod 600 ${path}`,
    );
  }
}

function readLegacyCredential(reference, Entry) {
  if (process.platform !== "darwin") {
    return new Entry(reference.service, reference.account || "").getPassword() || undefined;
  }
  const args = ["find-generic-password"];
  if (reference.account) args.push("-a", reference.account);
  args.push("-s", reference.service, "-w");
  const result = spawnSync("/usr/bin/security", args, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  });
  return result.status === 0 ? result.stdout.trim() || undefined : undefined;
}

