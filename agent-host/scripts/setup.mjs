async function askVisible(terminal, label, current) {
  const hint = current ? ` [${current}]` : "";
  const answer = (await terminal.question(`${label}${hint}: `)).trim();
  return answer || current;
}

async function askSecret(terminal, output, label, current) {
  stdout.write(`${label}${current ? " [configured; Enter keeps it]" : ""}: `);
  output.muted = true;
  const answer = (await terminal.question("")).trim();
  output.muted = false;
  stdout.write("\n");
  return answer || current;
}

async function askChoice(terminal, label, choices, defaultId) {
  stdout.write(`\n${label}\n`);
  for (const [id, description] of choices) {
    stdout.write(`  ${id === defaultId ? "*" : " "} ${id} — ${description}\n`);
  }
  const answer = (await terminal.question(`Choice [${defaultId}]: `)).trim();
  const selected = answer || defaultId;
  const byNumber = choices[Number(selected) - 1]?.[0];
  const byId = choices.find(([id]) => id === selected)?.[0];
  const value = byId || byNumber;
  if (!value) throw new Error(`Invalid choice for ${label}: ${selected}`);
  return value;
}

async function askYesNo(terminal, label, current) {
  const defaultValue = current ? "Y/n" : "y/N";
  const answer = (await terminal.question(`${label} [${defaultValue}]: `))
    .trim()
    .toLowerCase();
  if (!answer) return current;
  if (["y", "yes"].includes(answer)) return true;
  if (["n", "no"].includes(answer)) return false;
  throw new Error(`Please answer yes or no for ${label}`);
}

class MutedOutput extends Writable {
  muted = false;

  _write(chunk, encoding, callback) {
    if (!this.muted) stdout.write(chunk, encoding);
    callback();
  }
}

function parseEnv(text) {
  const values = {};
  for (const rawLine of text.split(/\r?\n/u)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#") || !line.includes("=")) continue;
    const separator = line.indexOf("=");
    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (key) values[key] = value;
  }
  return values;
}

function writeConfig(original, values, path) {
  const updates = new Map();
  for (const [key, value] of Object.entries(values)) {
    if (value === null && isSecretConfigKey(key)) continue;
    // Do not fill a fresh local config with dozens of empty Hub tombstones.
    // A tombstone is needed only when the key exists in the file being
    // rewritten or in a lower-precedence legacy file that the canonical file
    // must mask.
    if (value === null && !hasConfigKey(original, key) && !legacyHasConfigKey(key, path)) {
      continue;
    }
    updates.set(key, value);
  }
  const lines = original
    .split(/\r?\n/u)
    .filter((line) => {
      const match = line.match(/^\s*([A-Z][A-Z0-9_]*)\s*=/u);
      if (!match) return true;
      return !isSecretConfigKey(match[1]);
    });
  const remaining = updates;
  const next = lines
    .map((line) => {
      const match = line.match(/^\s*([A-Z][A-Z0-9_]*)\s*=/u);
      if (!match || !remaining.has(match[1])) return line;
      const key = match[1];
      const value = remaining.get(key);
      remaining.delete(key);
      // Empty values are intentional tombstones: a new canonical
      // $DSH_HOME/.env must be able to mask a removed Hub/model setting that
      // still exists in a readable legacy file below it.
      return value === null ? `${key}=""` : `${key}=${dotenvValue(value)}`;
    })
    .filter((line) => line !== null);
  if (remaining.size) {
    if (next.at(-1)?.trim()) next.push("");
    for (const [key, value] of remaining) {
      next.push(`${key}=${value === null ? '""' : dotenvValue(value)}`);
    }
  }
  mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
  if (process.platform !== "win32") chmodSync(dirname(path), 0o700);
  const temporary = `${path}.${process.pid}.tmp`;
  writeFileSync(temporary, `${next.join("\n").replace(/\n+$/u, "")}\n`, {
    encoding: "utf8",
    mode: 0o600,
  });
  chmodSync(temporary, 0o600);
  renameSync(temporary, path);
  chmodSync(path, 0o600);
}

function hasConfigKey(text, key) {
  return text.split(/\r?\n/u).some((line) =>
    line.match(/^\s*([A-Z][A-Z0-9_]*)\s*=/u)?.[1] === key,
  );
}

function legacyHasConfigKey(key, targetPath) {
  // An explicitly selected config is an isolated user override. Do not let a
  // checkout-local legacy file add empty Hub rows to a fresh test/CI config;
  // callers that want migration should omit --config and let setup discover
  // the legacy source explicitly.
  if (args.explicitConfig) return false;
  const target = resolve(targetPath);
  return legacyConfigPaths.some((candidate) => {
    if (resolve(candidate) === target || !existsSync(candidate)) return false;
    try {
      return hasConfigKey(readFileSync(candidate, "utf8"), key);
    } catch {
      return false;
    }
  });
}

function isSecretConfigKey(key) {
  return (
    key === "LLM_API_KEY" ||
    (key.startsWith("AGENT_") &&
      /(API_KEY|PASSWORD|TOKEN|SECRET)(?:$|_)/u.test(key) &&
      !key.endsWith("_CREDENTIAL_SERVICE") &&
      !key.endsWith("_CREDENTIAL_ACCOUNT") &&
      !key.endsWith("_KEYCHAIN_SERVICE") &&
      !key.endsWith("_KEYCHAIN_ACCOUNT"))
  );
}

function dotenvValue(value) {
  if (!value.includes('"')) return `"${value}"`;
  if (!value.includes("'")) return `'${value}'`;
  throw new Error("Configuration values cannot contain both quote styles");
}

function validateUrl(value, label) {
  let parsed;
  try {
    parsed = new URL(value);
  } catch {
    throw new Error(`${label} must be a valid URL`);
  }
  if (!["http:", "https:"].includes(parsed.protocol)) {
    throw new Error(`${label} must use HTTP or HTTPS`);
  }
}

function rejectUnsupportedEnvCharacters(label, value) {
  if (/\r|\n/u.test(value)) throw new Error(`${label} cannot contain newlines`);
}

function looksLikePlaceholder(value) {
  return (
    value.startsWith("replace-with-") ||
    value === "your-model-id" ||
    value.includes("example.com")
  );
}

function assertNodeVersion() {
  const [major, minor] = process.versions.node.split(".").map(Number);
  if (major < 22 || (major === 22 && minor < 19)) {
    throw new Error(`Node.js 22.19 or newer is required; found ${process.versions.node}`);
  }
}

function npmCommand() {
  return process.platform === "win32" ? "npm.cmd" : "npm";
}

function run(command, args) {
  console.log(`\n> ${command} ${args.join(" ")}`);
  const windowsNpm = process.platform === "win32" && command === "npm.cmd";
  const executable = windowsNpm ? process.env.ComSpec || "cmd.exe" : command;
  const executableArgs = windowsNpm
    ? ["/d", "/c", "npm.cmd", ...args]
    : args;
  const result = spawnSync(executable, executableArgs, {
    cwd: agentHostDir,
    env: process.env,
    stdio: "inherit",
  });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}

main().catch((error) => {
  console.error(`\nSetup failed: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
});
